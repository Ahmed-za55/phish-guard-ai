import uuid
from typing import Dict, Any, List

class ActiveCounterIntelligence:
    """
    Active Counter-Intelligence & Threat Mitigation Core: Automatically generates 
    YARA rules for payload detection and Snort/Suricata network intrusion rules 
    upon verifying high-risk phishing vectors.
    """
    @staticmethod
    def generate_yara_rule(threat_name: str, indicators: List[str]) -> str:
        rule_id = str(uuid.uuid4()).replace("-", "_")
        return f"""
rule PhishGuard_AutoGenerated_{rule_id[:8]} {{
    meta:
        description = "Auto-generated counter-intelligence rule for {threat_name}"
        author = "PhishGuard AI Autonomous Defense Core"
        date = "2026-10-29"
    strings:
        $s1 = "{indicators[0] if indicators else 'phishing_vector'}" ascii nocase
    condition:
        any of them
}}
"""

    @staticmethod
    def generate_network_signature(url: str) -> str:
        domain = url.split("//")[-1].split("/")[0]
        return f'alert tcp any any -> any 80,443 (msg:"PhishGuard Autonomous Block: Malicious Domain {domain}"; content:"{domain}"; sid:999999; rev:1;)'